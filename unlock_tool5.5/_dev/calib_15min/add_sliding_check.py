# -*- coding: utf-8 -*-
"""写入滑轨归因检查到手册 §9.9.1 末尾"""
import io

p = 'AI工作手册.md'
t = io.open(p, encoding='utf-8').read()

anchor = '该游戏点击签名（如灵画师金圈，按校准流程实测一次）。'
if anchor not in t:
    print('!! 未找到锚点')
else:
    insert_after = t.index(anchor) + len(anchor)
    new_text = '''

**滑轨归因检查（每游戏终审必做，2026-09-02 教训）**：
部分游戏的入口栏为滑动重排式——新图标从底部/边缘滑入，把已有图标向上/向旁
顶移。这导致：
1. 同一图标的登场事件可能记在不同框位 id 下（滑入时在 A 框，重排后到了 B 框）；
2. 渲染层按框位查事件会漏判——框位无事件 ≠ 图标未登场。
AI 终审必须做以下检查：
  a) 逐对排查：相邻框位在相同时段出现"空→有"配"有→空"的成对事件，
     → 可能是同一图标在滑动，非两次独立事件；
  b) 用帧裁图逐帧目检：确认图标从哪个框位滑入、最终停在哪；
  c) 终审后在 icon_status.json 写入每图标的最终解锁状态与实际归属，
     渲染器据此生成正确报告，不再按框位自行推断；
  d) 报告中不使用"未解锁"描述已实际登场的图标——只描述真正带锁/未出现的。
灵画师教训：活动菜单被误锚到玩法入口（凭位置推断）、福利/新手礼包被误标
"未解锁"（事件记在滑入时的旧框位名下，渲染器按框位查不到）——均已纠正。'''
    t = t[:insert_after] + new_text + t[insert_after:]
    io.open(p, 'w', encoding='utf-8').write(t)
    print("滑轨归因检查已写入手册 §9.9.1 末尾")
    # 验证
    t2 = io.open(p, encoding='utf-8').read()
    print("验证:", '滑轨归因检查' in t2 and 'icon_status' in t2)
